export type IdiomaPublico = keyof typeof publicTranslations;

export function getNestedValuePublico(obj: Record<string, any>, path: string): string | undefined {
  const result = path.split(".").reduce((acc: any, part: string) => {
    if (acc && typeof acc === "object" && part in acc) {
      return acc[part];
    }
    return undefined;
  }, obj);

  return typeof result === "string" ? result : undefined;
}

export function tPublico(key: string, idioma: IdiomaPublico, params?: Record<string, string | number>): string {
  const diccionario = publicTranslations[idioma];
  let valor = getNestedValuePublico(diccionario, key);

  if (!valor) {
    const fallback = getNestedValuePublico(publicTranslations.es, key);
    valor = fallback ?? key;
  }

  if (params && valor) {
    return Object.entries(params).reduce((acc, [k, v]) => {
      return acc.replace(new RegExp(`\\{\\{${k}\\}\\}`, "g"), String(v));
    }, valor);
  }

  return valor ?? key;
}