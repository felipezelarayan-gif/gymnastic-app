export type Idioma = keyof typeof translations;

export function getNestedValue(obj: Record<string, any>, path: string): string | undefined {
  const result = path.split(".").reduce((acc: any, part: string) => {
    if (acc && typeof acc === "object" && part in acc) {
      return acc[part];
    }
    return undefined;
  }, obj);
  
  return typeof result === "string" ? result : undefined;
}

export function t(key: string, idioma: Idioma, params?: Record<string, string | number>): string {
  const diccionario = translations[idioma];
  let valor = getNestedValue(diccionario, key);
  
  if (!valor) {
    const fallback = getNestedValue(translations.es, key);
    valor = fallback ?? key;
  }
  
  if (params && valor) {
    return Object.entries(params).reduce((acc, [k, v]) => {
      return acc.replace(new RegExp(`\\{\\{${k}\\}\\}`, "g"), String(v));
    }, valor);
  }
  
  return valor ?? key;
}